"""Renders the documentation figures into a light and a dark SVG each.

A figure source in docs/figures/src carries layout and class names only. The fonts, sizes
and colours come from docs/figures/theme.json, so every figure in the project shares one
theme. For docs/figures/src/<name>.svg this writes docs/figures/<name>.svg and
docs/figures/<name>-dark.svg, each with its resolved style inlined: an SVG shown as an
image cannot load an external stylesheet.

Usage: python3 scripts/build_figures.py
"""

import json
import pathlib
import re
import sys

FIGURES = pathlib.Path(__file__).resolve().parent.parent / "docs" / "figures"
SOURCES = FIGURES / "src"
FLOWS = ("txs", "digests", "batches", "blocks", "control", "requests")

HEADER = """<!--
Copyright IBM Corp. All Rights Reserved.

SPDX-License-Identifier: Apache-2.0

Generated by scripts/build_figures.py from src/{name}.svg; edit the source and rebuild.
-->
"""


def main():
    theme = json.loads((FIGURES / "theme.json").read_text())
    sources = sorted(SOURCES.glob("*.svg"))
    if not sources:
        sys.exit("no figure sources in %s" % SOURCES)
    for src in sources:
        body = strip_header(src.read_text())
        if "<!-- theme -->" not in body:
            sys.exit("%s has no <!-- theme --> marker" % src)
        for mode, suffix in (("light", ""), ("dark", "-dark")):
            out = FIGURES / ("%s%s.svg" % (src.stem, suffix))
            css = style(theme, theme[mode])
            out.write_text(HEADER.format(name=src.stem) + body.replace("<!-- theme -->", "<style>%s</style>" % css))
            print("wrote", out.relative_to(FIGURES.parent.parent))


def style(theme, c):
    s = theme["sizes"]
    rules = [
        ("text", "font-family:%s;fill:%s;text-anchor:middle" % (theme["font"], c["text"])),
        (".node", "fill:%s;stroke:%s;stroke-width:1.5" % (c["node-fill"], c["node-stroke"])),
        (".ledger", "fill:%s;stroke:%s;stroke-width:1.5" % (c["node-fill"], c["node-stroke"])),
        (".node-label", "font-size:%dpx" % s["node-label"]),
        (".node-label-main", "font-size:%dpx" % s["node-label-main"]),
        (".node-label-small", "font-size:%dpx" % s["node-label-small"]),
        (".node-sub", "font-size:%dpx" % s["node-sub"]),
        (".group", "stroke:%s;stroke-width:2" % c["group-stroke"]),
        (".frame", "fill:none;stroke-dasharray:6 5"),
        (".group-label", "font-size:%dpx;fill:%s" % (s["group-label"], c["group-label"])),
        (".shard-1", "fill:%s" % c["shard-1"]),
        (".shard-2", "fill:%s" % c["shard-2"]),
        (".shard-3", "fill:%s" % c["shard-3"]),
        (".consensus", "fill:%s" % c["consensus"]),
        (".node.batches", "fill:%s" % c["batches-fill"]),
        (".primary", "fill:%s" % c["primary"]),
        (".flow", "fill:none;stroke-width:2.5"),
        (".flow.dashed", "stroke-dasharray:8 6"),
        (".flow-label", "font-size:%dpx;font-style:italic" % s["flow-label"]),
        (".note", "font-size:%dpx;fill:%s" % (s["note"], c["muted"])),
        (".small", "font-size:%dpx" % s["note"]),
        (".end", "text-anchor:end"),
        (".start", "text-anchor:start"),
    ]
    for f in FLOWS:
        rules += [(".flow.%s" % f, "stroke:%s" % c[f]),
                  (".flow-label.%s" % f, "fill:%s" % c[f]),
                  (".m-%s" % f, "fill:%s" % c[f])]
    return "".join("%s{%s}" % r for r in rules)


def strip_header(text):
    """Drops the source's own license comment; the output gets a fresh one."""
    return re.sub(r"^\s*<!--.*?-->\s*", "", text, count=1, flags=re.S)


if __name__ == "__main__":
    main()
